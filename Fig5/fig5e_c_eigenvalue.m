%% =========================================================
%% subplot 6
%
% Competitive community
%
% 横坐标：d
% 纵坐标：特征值模长
%
% 三条理论曲线：
%
% 1. ellipse 最右端点
%       legend: Right endpoint
%
% 2. real outlier（额外点，位于左侧）
%       legend: Left endpoint
%
% 3. 整个理论群落矩阵的最大模特征值
%       legend: Maximum modulus
%
% 同时画出 switching point d_star 的竖线
%
% ==========================================================

subplot(3,3,6)

set(gca,...
    'unit','centimeters',...
    'position',[16 4.5 4 3]);

hold on


% =========================================================
% d 的范围
% =========================================================

d_all = 0:0.001:2.5;


% =========================================================
% 1. ellipse 最右端点
%
% center = 1-d-E
%
% lambda_right
% =
% center+a
%
% =
% 1-d-E+a
% =========================================================

lambda_right_all = ...
    1-d_all-E+a;

rho_right_all = ...
    abs(lambda_right_all);


% =========================================================
% 2. real outlier
%
% lambda_outlier
% =
% 1-d+(S-1)E
%
% competitive 中这个额外点位于谱的左侧，
% 因此在 legend 中记作 Left endpoint
% =========================================================

lambda_outlier_all = ...
    1-d_all+(S-1)*E;

rho_outlier_all = ...
    abs(lambda_outlier_all);


% =========================================================
% ellipse 最左端点
%
% 不单独画这条线，
% 但是在计算整个 theoretical spectrum 的最大模时
% 必须把它包含进去
%
% lambda_left
% =
% 1-d-E-a
% =========================================================

lambda_left_all = ...
    1-d_all-E-a;

rho_left_all = ...
    abs(lambda_left_all);


% =========================================================
% 整个理论谱的最大模
%
% competitive 中：
%
% rho(d)
% =
% max{
%       |lambda_right|,
%       |lambda_left|,
%       |lambda_outlier|
%     }
%
% 因此这个结果是整个理论谱的严格上包络
% =========================================================

rho_max_theory_all = ...
    max(...
    [rho_right_all;...
     rho_left_all;...
     rho_outlier_all],...
    [],1);


% =========================================================
% 作图
% =========================================================

% ---------------------------------------------------------
% Right endpoint
% ---------------------------------------------------------

p1 = plot(...
    d_all,...
    rho_right_all,...
    '-',...
    'Color',[31,120,180]/255,...
    'LineWidth',1);


% ---------------------------------------------------------
% extra point
%
% legend 中写成 Left endpoint
% ---------------------------------------------------------

p2 = plot(...
    d_all,...
    rho_outlier_all,...
    '-',...
    'Color',[230,159,0]/255,...
    'LineWidth',1);


% ---------------------------------------------------------
% theoretical maximum modulus
% ---------------------------------------------------------

p3 = plot(...
    d_all,...
    rho_max_theory_all,...
    'k--',...
    'LineWidth',1.3);


