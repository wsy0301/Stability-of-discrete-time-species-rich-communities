%% =========================================================
% Random community
%
% 展示 d = 0.95, 1, 1.05 时的特征值分布
% 以及 dominant eigenvalue 从右端点向左端点的切换
%
% 重要：
% 三个 d 使用完全相同的 random interaction matrix
% 只改变 diagonal term (1-d)
% =========================================================

clear all
clc
close all

%% =========================================================
% Parameters
% ==========================================================

rng(1);

sigma = 0.05;
S = 100;

% 为了让理论圆大一点、图上更容易看清楚
% 如果你想保持原来的参数，可以改回 C = 0.3
C = 0.1;

% 理论圆半径
R = sigma*sqrt(S*C);


%% =========================================================
% 固定一个 random interaction matrix
%
% 这里只生成一次！
%
% A 的对角元 = 0
% 非对角元：
%
% probability C : N(0,sigma^2)
% probability 1-C : 0
% ==========================================================

A = sigma*randn(S,S);

Connectance_matrix = rand(S,S) <= C;

A = A .* Connectance_matrix;

% 对角元设为 0
A(logical(eye(S))) = 0;


%% =========================================================
% 固定矩阵 A 的特征值
%
% 后面：
%
% J(d) = A + (1-d)I
%
% 因此：
%
% lambda_i(d) = lambda_i(A) + (1-d)
% ==========================================================

lambda_A = eig(A);


%% =========================================================
% Figure
% ==========================================================

figure

