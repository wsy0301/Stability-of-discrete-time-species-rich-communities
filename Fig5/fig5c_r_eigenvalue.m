    [linspace(start_color(1),end_color(1),n_colors)',...
     linspace(start_color(2),end_color(2),n_colors)',...
     linspace(start_color(3),end_color(3),n_colors)'];

colormap(custom_colormap);


%% =========================================================
% 一些公共变量
% ==========================================================

theta = linspace(0,2*pi,1000);

r = (0:0.01:1)';
theta_circle = pi*(-1:0.01:1);

x_circle = r*cos(theta_circle);
y_circle = r*sin(theta_circle);

circle_value = x_circle.^2 + y_circle.^2;


%% =========================================================
%% subplot 1
%
% Random community
% d = 0.95
%
% 圆心在 +0.05
% 所以理论上右端点模最大
%% =========================================================

subplot(3,3,1)

set(gca,...
    'unit','centimeters',...
    'position',[2 11 3 3]);

hold on


% ---------------------------------------------------------
% 灰色不稳定区域
% ----------------------------------------------------------

point1 = [-2 2 2 -2];
point2 = [-2 -2 2 2];

Color = [0.75 0.75 0.75];

a = patch(point1,point2,Color);

set(a,...
    'EdgeColor','none',...
    'FaceAlpha',0.5);


% ---------------------------------------------------------
% 单位圆内部稳定区域
% ----------------------------------------------------------

p_circle = pcolor(...
    x_circle,...
    y_circle,...
    4.5*(1-circle_value));

set(p_circle,'LineStyle','none');


% ---------------------------------------------------------
% 单位圆边界
% ----------------------------------------------------------

plot(...
    cos(theta),...
    sin(theta),...
    '-',...
    'Color',[0.35 0.35 0.35],...
    'LineWidth',0.8);

plot([0 0],[-1.1 1.1],...
    '-',...
    'Color',[0.4 0.4 0.4],...
    'LineWidth',0.8);

% ---------------------------------------------------------
% 当前 d
% ----------------------------------------------------------

d = 0.95;

center = 1-d;


% ---------------------------------------------------------
% 实际特征值
%
% 使用同一个 lambda_A
% 只整体向右移动 0.05
% ----------------------------------------------------------

lambda_095 = lambda_A + center;

plot(...
    real(lambda_095),...
    imag(lambda_095),...
    '.',...
    'MarkerSize',7,...
    'MarkerEdgeColor',[31,120,180]/255);


% ---------------------------------------------------------
% 理论随机圆
% ----------------------------------------------------------

x_r = center + R*cos(theta);
y_r = R*sin(theta);

plot(...
    x_r,...
    y_r,...
    'k-',...
    'LineWidth',1);


% ---------------------------------------------------------
% 理论左右端点
% ----------------------------------------------------------

lambda_left_095  = center-R;
lambda_right_095 = center+R;

