%% =========================================================
% S-C stability boundary
%
% d = 0.5, 1, 1.5
%
% 四类群落：
% Random
% Exploitative
% Competitive
% Mutualistic
%
% 理论临界线全部画成连续实线
%% =========================================================

clear all
clc
close all


%% =========================================================
% Figure
%% =========================================================

figure
set(gcf,'unit','centimeters','position',[5 5 27 8]);


%% =========================================================
% 基本参数
%
% 原来的 seita = 4
%
% 因此
%
% sigma = 1/seita = 0.25
%% =========================================================

seita = 20;

sigma = 1/seita;


% |N(0,sigma^2)| 的均值
E_abs = sigma*sqrt(2/pi);


%% =========================================================
% Exploitative community 的相关系数
%
% E = 0
%
% V = C*sigma^2
%
% R = -C*E_abs^2
%
% 所以
%
% r = R/V = -2/pi
%% =========================================================

r_e = -2/pi;


%% =========================================================
% d=0.5
d=0.5;

subplot(1,3,1)
set(gca,'unit', 'centimeters', 'position', [2 1 4 4]);
set(gca,'FontSize',8) %坐标轴字体的大小
hold on
% C
%
% 现在画连续理论曲线，所以直接使用密集的 C
% =========================================================

% Random
C_r = linspace(0.001,0.25,100);

% Exploitative / Competitive / Mutualistic
C = linspace(0.001,0.25,500);

% =====================================================
    % 1. Random
    %
    % 圆心：
    %
    % c = 1-d
    %
    % 半径：
    %
    % B = sigma*sqrt(S*C)
    %
    % 稳定性临界条件：
    %
    % |1-d| + B = 1
    %
    % 因此：
    %
    % Bcrit = 1-|1-d|
% =====================================================

    Bcrit_r = 1-abs(1-d);


    % B = sigma*sqrt(S*C)
    %
    % 所以
    %
    % S = (B/sigma)^2 / C

 S_r = (Bcrit_r/sigma)^2 ./ C_r;


% h_r = plot(S_r,C_r,'d',"Color",[0 0.4470 0.7410],'Markersize',4,'LineWidth',1)

h_r = plot(...
    S_r,...
    C_r,...
    'd',...
    'Color',[0 0.4470 0.7410],...
    'MarkerSize',4,...
    'LineWidth',1,...
    'MarkerIndices',1:2:length(C_r));



% =====================================================
    % 2. Exploitative
    %
    % 利用 rho_exploitative_B
    %
    % 求解：
    %
    % rho_max(B,d,r_e) = 1
% =====================================================

    fun_B = @(B) rho_exploitative_B(B,d,r_e)-1;


    % 求临界 B
    Bcrit_e = fzero(fun_B,[0 10]);


    % B = sigma*sqrt(S*C)
    %
    % 得
    %
    % S = (B/sigma)^2 / C

    S_e = (Bcrit_e/sigma)^2 ./ C;


   % h_e = plot(S_e,C,'o',"Color",[0.8500 0.3250 0.0980],'Markersize',4,'LineWidth',1)
   h_e = plot(...
    S_e,...
    C,...
    'o',...
    'Color',[0.8500 0.3250 0.0980],...
    'MarkerSize',4,...
    'LineWidth',1,...
    'MarkerIndices',1:13:length(C));



% =====================================================
    % 3. Competitive
    %
    % 同时考虑：
    %
    % (1) 椭圆 bulk
    %
    % (2) outlier
    %
    % 总的最大模：
    %
    % rho_total = max(rho_bulk, |lambda_out|)
% =====================================================

    S_c = NaN(size(C));


    for k = 1:length(C)

        C_now = C(k);


      % -------------------------------------------------
        % 平均值 E
        %
        % Competitive:
        %
        % E < 0
      % -------------------------------------------------

        E = -C_now*E_abs;


      % -------------------------------------------------
        % 方差 V
     % -------------------------------------------------

        V = C_now*sigma^2-E^2;


      % -------------------------------------------------
        % Aij 和 Aji 的 covariance-related quantity
        %
        % Competitive:
        %
        % R > 0
      % -------------------------------------------------

        R = C_now*E_abs^2;


      % -------------------------------------------------
        % 椭圆相关系数
      % -------------------------------------------------

        r = (R-E^2)/V;


    % -------------------------------------------------
        % 给定 S，计算 bulk 最大模
        %
        % 椭圆中心：
        %
        % c = 1-d-E
        %
        % 半轴：
        %
        % a = sqrt(S*V)*(1+r)
        %
        % b = sqrt(S*V)*(1-r)
      % -------------------------------------------------

        rho_bulk = @(S) dominant_ellipse(...
            1-d-E,...
            sqrt(S*V)*(1+r),...
            sqrt(S*V)*(1-r));


      % -------------------------------------------------
        % outlier
        %
        % lambda_out =
        %
        % 1-d+(S-1)E
      % -------------------------------------------------

        rho_out = @(S) abs(1-d+(S-1)*E);


       % -------------------------------------------------
        % 整个谱的最大模
       % -------------------------------------------------

        rho_total = @(S) max(...
            rho_bulk(S),...
            rho_out(S));


        % -------------------------------------------------
        % 找 rho_total = 1
        % -------------------------------------------------

        S_c(k) = fzero(@(S) rho_total(S)-1,[1 1e7]);

    end


%h_c = plot(S_c,C,'s',"Color",[0.9290 0.6940 0.1250],'Markersize',5,'LineWidth',1)

h_c = plot(...
    S_c,...
    C,...
    's',...
    'Color',[0.9290 0.6940 0.1250],...
    'MarkerSize',4,...
    'LineWidth',1,...
    'MarkerIndices',1:10:length(C));




% =====================================================
    % 4. Mutualistic
    %
    % 同样同时考虑：
    %
    % bulk + outlier
% =====================================================

    S_m = NaN(size(C));


    for k = 1:length(C)

        C_now = C(k);


        % -------------------------------------------------
        % 平均值 E
        %
        % Mutualistic:
        %
        % E > 0
        % -------------------------------------------------

        E = C_now*E_abs;


        % -------------------------------------------------
        % 方差
        % -------------------------------------------------

        V = C_now*sigma^2-E^2;


        % -------------------------------------------------
        % Mutualistic:
        %
        % R > 0
        % -------------------------------------------------

        R = C_now*E_abs^2;


        % -------------------------------------------------
        % 椭圆相关系数
        % -------------------------------------------------

        r = (R-E^2)/V;


        % -------------------------------------------------
        % bulk 最大模
        % -------------------------------------------------

        rho_bulk = @(S) dominant_ellipse(...
            1-d-E,...
            sqrt(S*V)*(1+r),...
            sqrt(S*V)*(1-r));


        % -------------------------------------------------
        % outlier
        % -------------------------------------------------

        rho_out = @(S) abs(1-d+(S-1)*E);


        % -------------------------------------------------
        % 整体最大模
        % -------------------------------------------------

        rho_total = @(S) max(...
            rho_bulk(S),...
            rho_out(S));


        % -------------------------------------------------
        % 临界 S
        % -------------------------------------------------

        S_m(k) = fzero(@(S) rho_total(S)-1,[1 1e7]);

    end


    %h_m = plot(S_m,C,'+',"Color",[0.4940 0.1840 0.5560],'Markersize',4,'LineWidth',1)
    
h_m = plot(...
    S_m,...
    C,...
    '+',...
    'Color',[0.4940 0.1840 0.5560],...
    'MarkerSize',4,...
    'LineWidth',1,...
    'MarkerIndices',1:8:length(C));



 % =====================================================
    % 坐标轴设置
 % =========================================================

    axis([-50 1525 -0.01 0.26])

    xlabel('$$S$$',...
        'Interpreter','latex',...
        'FontSize',9);

    ylabel('$$C$$',...
        'Interpreter','latex',...
        'FontSize',9);


    title(['$$d=0.5$$'],...
        'Interpreter','latex',...
        'FontSize',9);


 % =====================================================
    % Legend
% =========================================================

    legend([h_r h_e h_c h_m],...
        {'Random',...
         'Exploitative',...
         'Competitive',...
         'Mutualistic'},...
        'FontSize',8,...
        'Location','best');


    legend boxoff

    box on


