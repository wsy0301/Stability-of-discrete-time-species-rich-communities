%% =========================================================
% Exploitative community
%
% 展示 d = 0.5, 1, 1.5 时的特征值分布
%
% 三个 d 使用完全相同的 predator-prey interaction matrix
% 只改变 diagonal term (1-d)
%
% 对理论椭圆：
%
% lambda(theta)
% =
% center + a_e*cos(theta) + i*b_e*sin(theta)
%
% 其中
%
% center = 1-d-E
%
% 对 |lambda(theta)| 求最大值：
%
% cos(theta*)
% =
% a_e*center/(b_e^2-a_e^2)
%
% 当 |cos(theta*)| < 1 时：
%
% 最大模点位于斜向椭圆弧上。
%
% 特别地：
%
% d = 1 时 center = 0，
% cos(theta*) = 0，
% 斜向极值点正好退化为上下端点 +/- i*b_e。
%
% 因此这里不再比较 vertical endpoint 和 arc 的模长，
% 而是直接根据 cos(theta*) 判断 dominant eigenvalue。
% ==========================================================

clear all
clc
%close all


%% =========================================================
% Parameters
% ==========================================================

rng(1);

sigma = 0.05;
S = 100;
C = 0.1;


%% =========================================================
% 构造固定的 predator-prey interaction matrix
% ==========================================================

M = zeros(S,S);


for i = 2:S

    for j = 1:i-1

        p1 = rand;

        if p1 <= C

            p2 = rand;

            if p2 <= 0.5

                M(i,j) = abs(normrnd(0,sigma));
                M(j,i) = -abs(normrnd(0,sigma));

            else

                M(i,j) = -abs(normrnd(0,sigma));
                M(j,i) = abs(normrnd(0,sigma));

            end

        end

    end

end


A_e = M;


%% =========================================================
% 固定矩阵 A_e 的特征值
%
% J(d)
% =
% A_e + (1-d)I
%
% 因此：
%
% lambda_i(d)
% =
% lambda_i(A_e) + (1-d)
% ==========================================================

lambda_A_e = eig(A_e);


%% =========================================================
% Exploitative community 理论椭圆参数
% ==========================================================

% half-normal distribution 的均值
E_abs = sigma*sqrt(2/pi);

% predator-prey 中 off-diagonal overall mean = 0
E = 0;

% variance
V = C*sigma^2-E^2;

% covariance between A_ij and A_ji
R = -C*E_abs^2;

% correlation coefficient
r_e = (R-E^2)/V;


%% ---------------------------------------------------------
% 理论椭圆两个半轴
%
% a_e : horizontal semi-axis
%
% b_e : vertical semi-axis
%
% 对 exploitative community：
%
% r_e < 0
%
% 所以：
%
% b_e > a_e
% ----------------------------------------------------------

a_e = sqrt(S*V)*(1+r_e);

b_e = sqrt(S*V)*(1-r_e);


fprintf('\n==============================================\n');
fprintf('Exploitative community\n');
fprintf('==============================================\n');

fprintf('r = %.6f\n',r_e);

fprintf('horizontal semi-axis a = %.6f\n',...
    a_e);

fprintf('vertical semi-axis   b = %.6f\n',...
    b_e);


%% =========================================================
% Figure
% ==========================================================

figure

set(gcf,...
    'unit','centimeters',...
    'position',[10 5 23 15]);


%% =========================================================
% 自定义 colormap
% ==========================================================

start_color = [253,174,107]/255;

end_color = [255,245,235]/255;

n_colors = 256;

custom_colormap = ...
    [linspace(start_color(1),end_color(1),n_colors)',...
     linspace(start_color(2),end_color(2),n_colors)',...
     linspace(start_color(3),end_color(3),n_colors)'];

colormap(custom_colormap);


%% =========================================================
% 公共变量
% ==========================================================

theta = linspace(0,2*pi,1000);


%% ---------------------------------------------------------
% 单位圆内部渐变
% ----------------------------------------------------------

r = (0:0.01:1)';

theta_circle = pi*(-1:0.01:1);

x_circle = r*cos(theta_circle);

y_circle = r*sin(theta_circle);

circle_value = ...
    x_circle.^2 + y_circle.^2;



%% =========================================================
% subplot 1
%
% Exploitative community
%
% d = 0.5
%
% 此时 center > 0
%
% 主导特征值应该位于右侧斜向弧
% ==========================================================

subplot(3,3,1)

set(gca,...
    'unit','centimeters',...
    'position',[2 11 3 3]);

hold on


% ---------------------------------------------------------
% 灰色不稳定区域
% ----------------------------------------------------------

point1 = [-2 2 2 -2];

point2 = [-2 -2 2 2];

Color = [0.75 0.75 0.75];

aa = patch(...
    point1,...
    point2,...
    Color);

set(aa,...
    'EdgeColor','none',...
    'FaceAlpha',0.5);


% ---------------------------------------------------------
% 单位圆内部稳定区域
% ----------------------------------------------------------

p_circle = pcolor(...
    x_circle,...
    y_circle,...
    4.5*(1-circle_value));

set(p_circle,...
    'LineStyle','none');


% ---------------------------------------------------------
% 单位圆边界
% ----------------------------------------------------------

plot(...
    cos(theta),...
    sin(theta),...
    '-',...
    'Color',[0.35 0.35 0.35],...
    'LineWidth',0.8);


% ---------------------------------------------------------
% 虚轴
%
% Re(lambda) = 0
% ----------------------------------------------------------

plot(...
    [0 0],...
    [-1.1 1.1],...
    '--',...
    'Color',[0.4 0.4 0.4],...
    'LineWidth',0.8);


% ---------------------------------------------------------
% d = 0.95
% ----------------------------------------------------------

d = 0.8;

center = 1-d-E;


%% ---------------------------------------------------------
% 实际特征值
% ----------------------------------------------------------

lambda_050 = ...
    lambda_A_e + (1-d);

plot(...
    real(lambda_050),...
    imag(lambda_050),...
    '.',...
    'MarkerSize',7,...
    'MarkerEdgeColor',[31,120,180]/255);


% ---------------------------------------------------------
% 理论 exploitative ellipse
% ----------------------------------------------------------

x_e = ...
    center + a_e*cos(theta);

y_e = ...
    b_e*sin(theta);

plot(...
    x_e,...
    y_e,...
    'k-',...
    'LineWidth',1);


% =========================================================
% dominant eigenvalue
%
% cos(theta*)
% =
%
% a_e*center/(b_e^2-a_e^2)
% ==========================================================

cos_theta_arc_050 = ...
    a_e*center / ...
    (b_e^2-a_e^2);


fprintf('\n----------------------------------------------\n');
fprintf('d = 0.50\n');

fprintf('cos(theta*) = %.8f\n',...
    cos_theta_arc_050);


% ---------------------------------------------------------
% 判断最大模点
% ----------------------------------------------------------

if abs(cos_theta_arc_050) < 1

    % =====================================================
    % 斜向极值点存在
    %
    % 因为 d ~= 1，
    % 所以它就是最大模点
    % =====================================================

    sin_theta_arc_050 = ...
        sqrt(1-cos_theta_arc_050^2);

    lambda_dom_050 = ...
        center ...
        + a_e*cos_theta_arc_050 ...
        + 1i*b_e*sin_theta_arc_050;

    dominant_type_050 = ...
        'oblique arc';

else

    % =====================================================
    % 如果斜向极值点不存在
    %
    % 最大值落在实轴端点
    % =====================================================

    lambda_right_050 = ...
        center + a_e;

    lambda_left_050 = ...
        center - a_e;


    if abs(lambda_right_050) >= ...
            abs(lambda_left_050)

        lambda_dom_050 = ...
            lambda_right_050;

    else

        lambda_dom_050 = ...
            lambda_left_050;

    end


    dominant_type_050 = ...
        'real-axis endpoint';

end


x_dom_050 = ...
    real(lambda_dom_050);

y_dom_050 = ...
    abs(imag(lambda_dom_050));


% ---------------------------------------------------------
% 标出 dominant conjugate pair
% ----------------------------------------------------------

plot(...
    x_dom_050,...
    y_dom_050,...
    'o',...
    'MarkerSize',3,...
    'MarkerFaceColor',[215,48,39]/255,...
    'MarkerEdgeColor','k',...
    'LineWidth',0.8);


if y_dom_050 > 0

    plot(...
        x_dom_050,...
        -y_dom_050,...
        'o',...
        'MarkerSize',3,...
        'MarkerFaceColor',[215,48,39]/255,...
        'MarkerEdgeColor','k',...
        'LineWidth',0.8);

end


% ---------------------------------------------------------
% 从原点连接 dominant eigenvalues
%
% 虚线长度就是 |lambda_dom|
% ----------------------------------------------------------

% plot(...
%     [0 x_dom_050],...
