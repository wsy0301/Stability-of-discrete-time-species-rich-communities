% 
% 
% if y_dom_050 > 0
% 
%     plot(...
%         [0 x_dom_050],...
%         [0 -y_dom_050],...
%         '--',...
%         'Color',[0.25 0.25 0.25],...
%         'LineWidth',0.7);
% 
% end
% 

% ---------------------------------------------------------
% 输出结果
% ----------------------------------------------------------

fprintf('dominant type = %s\n',...
    dominant_type_050);

fprintf('dominant eigenvalue = %.8f +/- %.8fi\n',...
    x_dom_050,...
    y_dom_050);

fprintf('|lambda_dom| = %.8f\n',...
    abs(lambda_dom_050));


% ---------------------------------------------------------
% 设置
% ----------------------------------------------------------

axis equal
axis([-0.45 0.45 -0.45 0.45])

xticks([-0.3 0 0.3]);

yticks([-0.3 0 0.3]);

box on

set(gca,...
    'FontSize',8,...
    'Layer','top');

xlabel('Real','FontSize',9);

ylabel('Imaginary','FontSize',9);

title(...
    '$d=0.8$',...
    'Interpreter','latex',...
    'FontSize',10);



