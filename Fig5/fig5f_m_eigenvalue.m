% 横坐标：d
% 纵坐标：特征值模长
%
% 三条理论曲线：
%
% 1. ellipse 左端点
% 2. real outlier
%    legend 中按照要求写成 Right endpoint
% 3. 整个理论群落矩阵的最大模特征值
%
% 并画出 d_star 的竖线
%
% ==========================================================

subplot(3,3,5)

set(gca,...
    'unit','centimeters',...
    'position',[9 5 4 3]);

hold on


% ---------------------------------------------------------
% d 的范围
% ---------------------------------------------------------

d_all = 0:0.001:2.5;


% =========================================================
% 1. ellipse 左端点
%
% lambda_left
% =
% 1-d-E-a
% =========================================================

lambda_left_all = ...
    1-d_all-E-a;

rho_left_all = ...
    abs(lambda_left_all);


% =========================================================
% 2. real outlier
%
% lambda_outlier
% =
% 1-d+(S-1)E
%
% legend 中按要求写成 Right endpoint
% =========================================================

lambda_outlier_all = ...
    1-d_all+(S-1)*E;

rho_outlier_all = ...
    abs(lambda_outlier_all);


% =========================================================
% ellipse 右端点
%
% 这里只用于计算整个理论谱的最大模，
% 不单独画出来
% =========================================================

lambda_right_ellipse_all = ...
    1-d_all-E+a;

rho_right_ellipse_all = ...
    abs(lambda_right_ellipse_all);


% =========================================================
% 3. 整个理论群落矩阵的最大模特征值
%
% rho(d)
% =
% max{
%   |lambda_left|,
%   |lambda_right_ellipse|,
%   |lambda_outlier|
% }
% =========================================================

rho_max_theory_all = ...
    max([rho_left_all;...
         rho_right_ellipse_all;...
         rho_outlier_all],[],1);


% =========================================================
% 作图
% =========================================================

p1 = plot(...
    d_all,...
    rho_left_all,...
    '-',...
    'Color',[230,159,0]/255,...
    'LineWidth',1);

p2 = plot(...
    d_all,...
    rho_outlier_all,...
    '-',...
    'Color',[31,120,180]/255,...
    'LineWidth',1);

p3 = plot(...
    d_all,...
    rho_max_theory_all,...
    'k--',...
    'LineWidth',1.3);


