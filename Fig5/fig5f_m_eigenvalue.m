%% =========================================================
% Mutualistic community
%
% 展示：
%
% d = d_star - 0.05
% d = d_star
% d = d_star + 0.05
%
% d_star 由
%
% |leftmost ellipse endpoint|
% =
% |real outlier|
%
% 精确得到
%
% 三个 d 使用完全相同的 mutualistic interaction matrix
% 只改变 diagonal term (1-d)
%
% ==========================================================

clear all
clc
close all


%% =========================================================
% Parameters
% ==========================================================

rng(1);

sigma = 0.05;
S = 100;
C = 0.1;


%% =========================================================
% 构造固定的 mutualistic interaction matrix
%
% 如果一对物种发生相互作用：
%
% A_ij > 0
% A_ji > 0
%
% ==========================================================

M = zeros(S,S);

for i = 2:S

    for j = 1:i-1

        p1 = rand;

        if p1 <= C

            M(i,j) = abs(normrnd(0,sigma));

            M(j,i) = abs(normrnd(0,sigma));

        end

    end

end


A_m = M;



%% =========================================================
% 固定矩阵 A_m 的特征值
%
% J(d)
% =
% A_m + (1-d)I
%
% 因此
%
% lambda_i(d)
% =
% lambda_i(A_m) + (1-d)
%
% ==========================================================

lambda_A_m = eig(A_m);



%% =========================================================
% Mutualistic community
% 理论谱参数
% ==========================================================

% half-normal distribution 的均值
E_abs = sigma*sqrt(2/pi);


% ---------------------------------------------------------
% mutualistic interaction 的 overall mean
% ---------------------------------------------------------

E = C*E_abs;


% ---------------------------------------------------------
% variance
% ---------------------------------------------------------

V = C*sigma^2-E^2;


% ---------------------------------------------------------
% E[A_ij A_ji]
%
% mutualistic 中 A_ij 和 A_ji 同号
%
% R > 0
% ---------------------------------------------------------

R = C*E_abs^2;


% ---------------------------------------------------------
% correlation coefficient
% ---------------------------------------------------------

r_m = (R-E^2)/V;



%% =========================================================
% Mutualistic ellipse 的两个半轴
%
% a : horizontal semi-axis
% b : vertical semi-axis
%
% mutualistic:
%
% r_m > 0
%
% 因此
%
% a > b
%
% 椭圆沿实轴方向拉长
% ==========================================================

a = sqrt(S*V)*(1+r_m);

b = sqrt(S*V)*(1-r_m);



%% =========================================================
% 计算 dominant eigenvalue switching point
%
% theoretical ellipse center:
%
% c = 1-d-E
%
%
% ellipse 最左端点：
%
% lambda_left
% =
% 1-d-E-a
%
%
% real outlier：
%
% lambda_outlier
% =
% 1-d+(S-1)E
%
%
% 在稳定性最大的位置：
%
% |lambda_left|
% =
% |lambda_outlier|
%
%
% 此时：
%
% lambda_left < 0
%
% lambda_outlier > 0
%
%
% 因此：
%
% 1-d+(S-1)E
%
% =
%
% -[1-d-E-a]
%
%
% 得到：
%
% d_star
% =
%
% 1 + [(S-2)E-a]/2
%
% ==========================================================

d_star = ...
    1 + ((S-2)*E-a)/2;



%% =========================================================
% 三个用于画图的 d
% ==========================================================

d1 = d_star-0.05;

d2 = d_star;

d3 = d_star+0.05;



%% =========================================================
% 检查 d_star 处两个模长是否相等
% ==========================================================

center_star = ...
    1-d_star-E;


lambda_left_star = ...
    center_star-a;


lambda_outlier_star = ...
    1-d_star+(S-1)*E;


rho_left_star = ...
    abs(lambda_left_star);


rho_outlier_star = ...
    abs(lambda_outlier_star);



%% =========================================================
% 输出理论参数
% ==========================================================

fprintf('\n==============================================\n');

fprintf('Mutualistic community\n');

fprintf('==============================================\n');

fprintf('E = %.8f\n',E);

fprintf('V = %.8f\n',V);

fprintf('R = %.8f\n',R);

fprintf('r = %.8f\n',r_m);

fprintf('horizontal semi-axis a = %.8f\n',a);

fprintf('vertical semi-axis   b = %.8f\n',b);


fprintf('\n----------------------------------------------\n');

fprintf('Switching point\n');

fprintf('----------------------------------------------\n');

fprintf('d_star = %.8f\n',d_star);

fprintf('lambda_left(d_star)    = %.8f\n',...
