% =========================================================
% ellipse 左右两个实轴端点
% ==========================================================

lambda_right_1 = ...
    center+a;

lambda_left_1 = ...
    center-a;



% =========================================================
% real outlier
% ==========================================================

lambda_outlier_1 = ...
    1-d+(S-1)*E;



% =========================================================
% 椭圆自身的精确最大模
%
% mutualistic 中 a > b
%
% 所以最大模一定位于左右实轴端点之一
% ==========================================================

if abs(lambda_right_1) >= abs(lambda_left_1)

    lambda_ell_1 = ...
        lambda_right_1;

else

    lambda_ell_1 = ...
        lambda_left_1;

end


rho_ell_1 = ...
    abs(lambda_ell_1);


rho_outlier_1 = ...
    abs(lambda_outlier_1);



% =========================================================
% 整个谱的 dominant eigenvalue
% ==========================================================

if rho_ell_1 >= rho_outlier_1

    lambda_dom_1 = ...
        lambda_ell_1;

    dominant_type_1 = ...
        'ellipse endpoint';

else

    lambda_dom_1 = ...
        lambda_outlier_1;

    dominant_type_1 = ...
        'outlier';

end



