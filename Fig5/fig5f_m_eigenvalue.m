fprintf('Three values of d\n');

fprintf('----------------------------------------------\n');

fprintf('d1 = d_star - 0.05 = %.8f\n',d1);

fprintf('d2 = d_star        = %.8f\n',d2);

fprintf('d3 = d_star + 0.05 = %.8f\n',d3);



