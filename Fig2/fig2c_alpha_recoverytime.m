    'Competitive (-/-)',...
    'Mutualistic (+/+)'},...
    'FontSize',8)

legend boxoff


xlabel(...
    '$$\alpha$$',...
    'Interpreter','latex',...
    'FontSize',9)


ylabel(...
    'Recovery time',...
    'FontSize',9)


box on