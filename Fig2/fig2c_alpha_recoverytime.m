    end

end



%% =========================================================
% Plot competitive
%% =========================================================

h_c = plot(...
    alpha_c,...
    recoverytime_c,...
    'square',...
    'MarkerEdgeColor',[0.9290 0.6940 0.1250],...
    'MarkerSize',5,...
    'LineWidth',1);



%% =========================================================
%% 3. Mutualistic community (+/+)
%% =========================================================

alpha_m = [];

recoverytime_m = [];

number_m = 1;


for w = 1:n_realization


