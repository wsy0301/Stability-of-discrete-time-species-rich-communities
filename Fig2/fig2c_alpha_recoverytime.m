%% =========================================================
% alpha 与 recovery time 的关系
%
% 三类群落：
% 1. Exploitative (+/-)
% 2. Competitive (-/-)
% 3. Mutualistic (+/+)
%
% 修改：
% 1. 固定初始扰动的总欧式距离 D0
% 2. 随机扰动方向并归一化
% 3. 三类群落使用完全相同的初始扰动
% 4. Recovery time 定义为：
%
%    ||X(t)-X*||_2 <= 0.005*D0
%
%    时首次达到的时间
%% =========================================================

clear all
clc


%% =========================================================
% Figure
%% =========================================================

figure
set(gcf,'unit','centimeters','position',[15 5 9 6])

subplot(1,1,1)

set(gca,...
    'unit','centimeters',...
    'position',[1.5 1 5 3.5],...
    'FontSize',8)

hold on


%% =========================================================
% Basic parameters
%% =========================================================

S = 3;

d = 1;

X_e = ones(S,1);

n_realization = 100;


%% =========================================================
% Fixed initial perturbation
%
% 固定总欧式扰动强度：
%
% ||X0-X*||_2 = D0_fixed
%
%% =========================================================

D0_fixed = 0.3;


% ---------------------------------------------------------
% 随机产生一个扰动方向
% ---------------------------------------------------------

direction = randn(S,1);

direction = direction / norm(direction,2);


% ---------------------------------------------------------
% 初始状态
% ---------------------------------------------------------

X_0 = X_e + D0_fixed*direction;


% ---------------------------------------------------------
% 实际初始扰动强度
%
% 理论上应该恰好等于 D0_fixed
% ---------------------------------------------------------

D0 = norm(X_0-X_e,2);


%% =========================================================
% Recovery criterion
%
% 恢复：
%
% ||X(t)-X*||_2 <= 0.005 D0
%
%% =========================================================

recovery_fraction = 0.005;

recovery_threshold = recovery_fraction*D0;


% 最大模拟时间
%
% 原来的100步在 alpha 接近0.05时可能稍短，
% 因此这里增加到500步
% ---------------------------------------------------------

i_max = 500;



%% =========================================================
%% 1. Exploitative community (+/-)
%% =========================================================

alpha_e = [];

recoverytime_e = [];

number_e = 1;


for w = 1:n_realization


    %% -----------------------------------------------------
    % Generate interaction matrix A
    %% -----------------------------------------------------

    A = zeros(S);


    for i = 1:S

        for j = 1:S

            if i == j

                A(i,j) = -d;

            elseif i > j

                p1 = rand;


                if p1 <= 0.5

                    A(i,j) = abs(rand);
                    A(j,i) = -abs(rand);

                else

                    A(i,j) = -abs(rand);
                    A(j,i) = abs(rand);

                end

            end

        end

    end



    %% -----------------------------------------------------
    % Community matrix
    %
    % M = I + diag(X*) A
    %% -----------------------------------------------------

    M = eye(S) + diag(X_e)*A;


    rho_M = max(abs(eig(M)));

    alpha_M = -log(rho_M);



    %% -----------------------------------------------------
    % 只考虑局部稳定并且 alpha > 0.05 的系统
    %% -----------------------------------------------------

    if alpha_M > 0.05


        A_stability = A;


        %% -------------------------------------------------
        % 根据固定平衡点 X*=1 反推出 r
        %
        % r + A X* = 0
        %% -------------------------------------------------

        r = -A_stability*X_e;



        %% -------------------------------------------------
        % Ricker dynamics
        %
        % X(t+1)
        % =
        % diag(X(t))*exp(r+A*X(t))
        %% -------------------------------------------------

        X = X_0;


        recovery_time = NaN;


        for t = 1:i_max


            X = diag(X)*exp(...
                r + A_stability*X);


            %% ---------------------------------------------
            % 当前状态与平衡点之间的欧式距离
            %% ---------------------------------------------

            distance = norm(X-X_e,2);


            %% ---------------------------------------------
            % 第一次进入初始扰动的0.5%以内
            %% ---------------------------------------------

            if distance <= recovery_threshold

                recovery_time = t;

                break

            end

        end



        %% -------------------------------------------------
        % 只有在模拟时间内恢复的系统才记录
        %% -------------------------------------------------

        if ~isnan(recovery_time)

            alpha_e(number_e,1) = alpha_M;

            recoverytime_e(number_e,1) = recovery_time;

            number_e = number_e + 1;

        end

    end

end



%% =========================================================
% Plot exploitative
%% =========================================================

h_e = plot(...
    alpha_e,...
    recoverytime_e,...
    'o',...
    'MarkerEdgeColor',[0.8500 0.3250 0.0980],...
    'MarkerSize',5,...
    'LineWidth',1);



%% =========================================================
%% 2. Competitive community (-/-)
%% =========================================================

alpha_c = [];

recoverytime_c = [];

number_c = 1;


for w = 1:n_realization


